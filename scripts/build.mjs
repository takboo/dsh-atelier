import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFile } from 'node:fs/promises';

export async function buildClient() {
  const { name } = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
  await build({
    absWorkingDir: fileURLToPath(new URL('..', import.meta.url)),
    entryPoints: ['src/client.js'], outfile: 'client.js', bundle: true, format: 'cjs',
    platform: 'browser', target: 'es2022', external: ['react'], loader: { '.css': 'text' },
    banner: { js: '// Generated by npm run build. Edit src/ instead.\nwindow.__ModuleLoader__.load({ id: ' + JSON.stringify(name) + ', factory(require) {\nconst module = { exports: {} };' },
    footer: { js: 'return module.exports;\n}});' },
  });
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await buildClient();
